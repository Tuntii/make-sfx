export function getPreset(id: string): SoundParams | undefined {
  return presets[id as PresetId];
}

export function listPresets(): PresetMeta[] {
  return presetCatalog;
}

export function findPresetsByTag(tag: string): PresetMeta[] {
  const q = tag.toLowerCase();
  return presetCatalog.filter((p) =>
    p.tags.some((t) => t.toLowerCase().includes(q)),
  );
}