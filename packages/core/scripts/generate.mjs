// Generates src/generated/ from wasm/makesfx.wasm (runs before build and test):
//
//   wasm-binary.ts  the module as base64, so the package loads the engine
//                   without fs, fetch or bundler asset handling (Node,
//                   browsers, workers, Deno, Bun)
//   registry.ts     parameter tables, the SoundParams / FxParams /
//                   MasterParams / TextureParams types and their defaults,
//                   from the engine registry (engine/src/legacy/registry.cpp)
//
// wasm/makesfx.wasm is built from engine/ (`cmake --build --preset wasm`) and
// committed; CI checks that it matches a fresh build.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src", "generated");
const wasm = readFileSync(join(root, "wasm", "makesfx.wasm"));
const sha256 = createHash("sha256").update(wasm).digest("hex");
const header = "// Generated by scripts/generate.mjs from wasm/makesfx.wasm — do not edit.\n";

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "wasm-binary.ts"),
  // Typed as string so the declaration file does not repeat the literal.
  `${header}export const WASM_SHA256: string = "${sha256}";\nexport const WASM_BASE64: string =\n  "${wasm.toString("base64")}";\n`,
);

// ── Registry ────────────────────────────────────────────────────────────────

const { exports: engine } = new WebAssembly.Instance(new WebAssembly.Module(wasm), {
  env: { emscripten_notify_memory_growth() {} },
});
engine._initialize();
const heap = new Uint8Array(engine.memory.buffer);
const ptr = engine.msfx_parameters_json();
let end = ptr;
while (heap[end] !== 0) end++;
const { sfx } = JSON.parse(new TextDecoder().decode(heap.subarray(ptr, end)));

const json = (v) => JSON.stringify(v, null, 2);
const blocks = [
  { prefix: "params.", type: "SoundParams", defaults: "DEFAULT_SOUND_PARAMS", doc: "ZzFX synthesis parameters with human-readable names." },
  { prefix: "fx.", type: "FxParams", defaults: "DEFAULT_FX_PARAMS", doc: "Post-processing: EQ, saturation, compression, delay, reverb, limiter, stereo width." },
  { prefix: "master.", type: "MasterParams", defaults: "DEFAULT_MASTER_PARAMS", doc: "Master timing — control total SFX length." },
  { prefix: "texture.", type: "TextureParams", defaults: "DEFAULT_TEXTURE_PARAMS", doc: "Post-synth texture processing." },
];

let out = `${header}// Source: engine/src/legacy/registry.cpp, read through msfx_parameters_json().

export interface RegistryParam {
  /** SoundConfig path, e.g. "params.volume", "oscillators[].mix" ("[]": any slot). */
  path: string;
  group: ParamGroup;
  /** Layer and LFO entries use "{n}" for the slot number shown in UIs. */
  label: string;
  labelTr: string;
  min: number;
  max: number;
  step: number;
  default: number;
  unit?: string;
  description: string;
  aiHint: string;
}

export type ParamGroup = ${sfx.groups.map((g) => JSON.stringify(g.id)).join(" | ")};

export const SFX_GROUPS = ${json(sfx.groups)} as const;

export const SFX_WAVE_SHAPES = ${json(sfx.waveShapes)} as const;

export const SFX_MODULATOR_TARGETS = ${json(sfx.modulatorTargets)} as const;

export const SFX_PARAMS: readonly RegistryParam[] = ${json(sfx.params)};
`;

for (const block of blocks) {
  const fields = sfx.params.filter((p) => p.path.startsWith(block.prefix) && !p.path.includes(".", block.prefix.length));
  const key = (p) => p.path.slice(block.prefix.length);
  const range = (p) => `${p.min}–${p.max}${p.unit ? ` ${p.unit}` : ""}, default ${p.default}`;
  out += `\n/** ${block.doc} */\nexport interface ${block.type} {\n`;
  for (const p of fields) out += `  /** ${p.description} (${range(p)}) */\n  ${key(p)}?: number;\n`;
  out += `}\n\nexport const ${block.defaults}: Required<${block.type}> = {\n`;
  for (const p of fields) out += `  ${key(p)}: ${p.default},\n`;
  out += "};\n";
}
writeFileSync(join(outDir, "registry.ts"), out);

console.log(`generated src/generated (makesfx.wasm ${wasm.length} bytes, sha256 ${sha256.slice(0, 12)}; ${sfx.params.length} registry params)`);
