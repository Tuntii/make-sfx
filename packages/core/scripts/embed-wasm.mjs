// Embeds wasm/makesfx.wasm into src/generated/wasm-binary.ts as base64, so the
// package loads the engine without fs, fetch or bundler asset handling — in
// Node, browsers, workers, Deno and Bun alike. Runs before build and test.
//
// wasm/makesfx.wasm is built from engine/ (`cmake --build --preset wasm`) and
// committed; CI checks that it matches a fresh build.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const wasm = readFileSync(join(root, "wasm", "makesfx.wasm"));
const sha256 = createHash("sha256").update(wasm).digest("hex");
const out = join(root, "src", "generated", "wasm-binary.ts");

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/embed-wasm.mjs from wasm/makesfx.wasm — do not edit.\n` +
    `export const WASM_SHA256 = "${sha256}";\n` +
    `export const WASM_BASE64 =\n  "${wasm.toString("base64")}";\n`,
);
console.log(`embedded makesfx.wasm (${wasm.length} bytes, sha256 ${sha256.slice(0, 12)})`);
